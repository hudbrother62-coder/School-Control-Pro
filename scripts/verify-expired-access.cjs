const assert=require("node:assert/strict");
const fs=require("node:fs");
const read=p=>fs.readFileSync(p,"utf8");
const app=read("app/app/page.tsx");
const wall=read("components/PaymentWall.tsx");
const form=read("components/FormulirPayment.tsx");
const css=read("components/formulir-checkout.css");
assert(app.includes('subscription?.status==="trial"?subscription.trial_ends_at'),"Valid trials must remain eligible for workspace access");
assert(app.includes('entitlement===true&&!!accessDeadline'),"Client access must still require server entitlement");
assert(app.includes('<PaymentWall schoolId={schoolId}'),"Expired schools should enter an in-app recovery screen");
assert(wall.includes('Masa Demo Sekolapro Telah Berakhir'),"Expired trial must have distinct notice");
assert(wall.includes('Akses Sekolah Sedang Dinonaktifkan'),"Admin-paused account must have distinct notice");
assert(wall.includes('owner?<FormulirPayment')&&wall.includes('!paused&&'),"Checkout must be owner-only and unavailable for paused schools");
assert(form.includes('https://profit-meledak.store/sekolapro'),"Use owner-provided checkout URL");
assert(form.includes('src={CHECKOUT_URL}')&&form.includes('target="_blank"'),"Provide in-app iframe and direct browser fallback");
assert(form.includes('sandbox="allow-scripts allow-same-origin allow-forms')&&form.includes('allow="payment *"'),"Sandbox payment embed properly");
assert(form.includes('Pembayaran tidak otomatis mengaktifkan akun')&&form.includes('Super Admin mengonfirmasi'),"Checkout must never unlock paid access");
assert(!form.includes('sc_platform_confirm_renewal')&&!form.includes('SUPABASE_SERVICE_ROLE_KEY'),"No client authority to confirm payments");
assert(css.includes('@media(max-width:680px)'),"Checkout modal must support narrow screens");
console.log("PASS: live Formulir checkout, owner restriction, distinct expiration statuses, manual admin activation, valid trial access.");
